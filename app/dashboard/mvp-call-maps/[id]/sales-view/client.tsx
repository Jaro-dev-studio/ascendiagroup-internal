// Custom Node Components
function PageNode({ data, id }: { data: PageNodeData; id: string }) {
  const [showMenu, setShowMenu] = useState(false);
  const [showEditDialog, setShowEditDialog] = useState(false);
  const [name, setName] = useState(data.name);
  const [description, setDescription] = useState(data.description);
  const [successCriteria, setSuccessCriteria] = useState<SuccessCriterion[]>(data.successCriteria || []);
  const [newCriterion, setNewCriterion] = useState("");
  const [isGenerating, setIsGenerating] = useState(false);
  const menuRef = useRef<HTMLDivElement>(null);
  const { setNodes, setEdges } = useReactFlow();

  // Check if this is the included dashboard or auto-generated pages
  const isIncluded = id === "dashboard-included";
  const isAutoGenerated = id === "landing-page-auto" || id === "org-settings-included" || id === "user-settings-included";
  const isEntityPage = id.startsWith("entity-") && (id.endsWith("-list") || id.endsWith("-detail"));
  const isSettingsPage = id === "org-settings-included" || id === "user-settings-included";
  const isProtected = isIncluded; // Only dashboard cannot be deleted, settings pages can be deleted and re-added

  useEffect(() => {
    const handleClickOutside = (event: MouseEvent) => {
      if (menuRef.current && !menuRef.current.contains(event.target as HTMLElement)) {
        setShowMenu(false);
      }
    };
    document.addEventListener("mousedown", handleClickOutside);
    return () => document.removeEventListener("mousedown", handleClickOutside);
  }, []);

  const handleDelete = () => {
    if (isProtected) return; // Cannot delete protected nodes
    setNodes((nodes) => nodes.filter((node) => node.id !== id));
    setEdges((edges) => edges.filter((edge) => edge.source !== id && edge.target !== id));
    setShowMenu(false);
  };

  const handleDisconnectIncoming = () => {
    setEdges((edges) => edges.filter((edge) => edge.target !== id));
    setShowMenu(false);
  };

  const handleDisconnectOutgoing = () => {
    setEdges((edges) => edges.filter((edge) => edge.source !== id));
    setShowMenu(false);
  };

  const handleSave = () => {
    setNodes((nodes) =>
      nodes.map((node) =>
        node.id === id
          ? { ...node, data: { ...node.data, name, description, successCriteria } }
          : node
      )
    );
    setShowEditDialog(false);
  };

  const handleAddCriterion = () => {
    if (!newCriterion.trim()) return;
    setSuccessCriteria([...successCriteria, { id: `sc-${Date.now()}`, text: newCriterion.trim() }]);
    setNewCriterion("");
  };

  const handleRemoveCriterion = (criterionId: string) => {
    setSuccessCriteria(successCriteria.filter((c) => c.id !== criterionId));
  };

  const handleGenerateCriteria = async () => {
    setIsGenerating(true);
    try {
      const response = await fetch("/api/generate-success-criteria", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          blockType: "page",
          name,
          description,
          existingCriteria: successCriteria.map((c) => c.text),
        }),
      });
      if (!response.ok) throw new Error("Failed to generate");
      const { criteria } = await response.json();
      const newCriteria = criteria.map((text: string) => ({
        id: `sc-${Date.now()}-${Math.random().toString(36).substr(2, 9)}`,
        text,
      }));
      setSuccessCriteria([...successCriteria, ...newCriteria]);
    } catch (error) {
      console.error("Failed to generate criteria:", error);
    } finally {
      setIsGenerating(false);
    }
  };

  const criteriaCount = data.successCriteria?.length || 0;

  return (
    <div className={cn(
      "relative min-w-[200px] rounded-lg border-2 bg-white p-4 shadow-lg",
      isProtected ? "border-primary-500 ring-2 ring-primary-200" : "border-primary-300"
    )}>
      <Handle
        type="target"
        position={Position.Left}
        className="!size-4 !border-2 !border-primary-500 !bg-white hover:!bg-primary-100"
      />
      <Handle
        type="source"
        position={Position.Right}
        className="!size-4 !border-2 !border-primary-500 !bg-white hover:!bg-primary-100"
      />

      <div className="absolute right-2 top-2">
        <Button
          variant="ghost"
          size="icon"
          className="size-6"
          onClick={() => setShowMenu(!showMenu)}
        >
          <MoreVertical className="size-4" />
        </Button>
      </div>

      {showMenu && (
        <div
          ref={menuRef}
          className="absolute right-2 top-8 z-50 min-w-40 rounded-lg border border-secondary-200 bg-white p-1 shadow-lg"
        >
          <button
            className="flex w-full items-center gap-2 rounded px-2 py-1.5 text-sm hover:bg-secondary-100"
            onClick={() => {
              setShowEditDialog(true);
              setShowMenu(false);
            }}
          >
            <Edit2 className="size-3" /> Edit
          </button>
          <button
            className="flex w-full items-center gap-2 rounded px-2 py-1.5 text-sm hover:bg-secondary-100"
            onClick={handleDisconnectIncoming}
          >
            <ArrowLeftFromLine className="size-3" /> Disconnect Incoming
          </button>
          <button
            className="flex w-full items-center gap-2 rounded px-2 py-1.5 text-sm hover:bg-secondary-100"
            onClick={handleDisconnectOutgoing}
          >
            <ArrowRightFromLine className="size-3" /> Disconnect Outgoing
          </button>
          {!isProtected && (
            <button
              className="flex w-full items-center gap-2 rounded px-2 py-1.5 text-sm text-danger-600 hover:bg-danger-50"
              onClick={handleDelete}
            >
              <Trash2 className="size-3" /> Delete
            </button>
          )}
        </div>
      )}

      <div className="flex items-center gap-2">
        <div className="flex size-8 items-center justify-center rounded-lg bg-primary-100">
          <FileCode className="size-4 text-primary-600" />
        </div>
        <div className="flex items-center gap-1">
          <Badge variant="outline" className="text-xs">
            Page
          </Badge>
          {isIncluded && (
            <Badge className="bg-primary-600 text-xs text-white">
              Included
            </Badge>
          )}
          {isAutoGenerated && (
            <Badge className="bg-success-600 text-xs text-white">
              Auto
            </Badge>
          )}
          {isEntityPage && (
            <Badge className="bg-secondary-600 text-xs text-white">
              Entity
            </Badge>
          )}
        </div>
      </div>
      <h3 className="mt-2 font-medium text-secondary-900">{data.name}</h3>
      {data.description && (
        <p className="mt-1 text-xs text-secondary-500">{data.description}</p>
      )}
      {criteriaCount > 0 && (
        <div className="mt-2 flex items-center gap-1 text-xs text-success-600">
          <ClipboardCheck className="size-3" />
          {criteriaCount} success criteria
        </div>
      )}

      <Dialog open={showEditDialog} onOpenChange={setShowEditDialog}>
        <DialogContent className="max-w-lg">
          <DialogHeader>
            <DialogTitle>Edit Page</DialogTitle>
            {isIncluded && (
              <DialogDescription>
                This is a system page. You can add success criteria but cannot change the name.
              </DialogDescription>
            )}
          </DialogHeader>
          <div className="space-y-4">
            <div className="space-y-2">
              <Label>Page Name</Label>
              <Input
                value={name}
                onChange={(e) => setName(e.target.value)}
                placeholder="e.g., Dashboard"
                disabled={isIncluded}
              />
            </div>
            <div className="space-y-2">
              <Label>Description</Label>
              <Input
                value={description}
                onChange={(e) => setDescription(e.target.value)}
                placeholder="Brief description of the page"
                disabled={isIncluded}
              />
            </div>
            <div className="space-y-2">
              <Label className="flex items-center gap-1">
                <ClipboardCheck className="size-4" />
                Success Criteria
              </Label>
              <p className="text-xs text-secondary-500">
                Define what success looks like for this page
              </p>
              <div className="max-h-40 space-y-2 overflow-y-auto">
                {successCriteria.map((criterion) => (
                  <div
                    key={criterion.id}
                    className="flex items-center gap-2 rounded border border-secondary-200 bg-secondary-50 p-2 text-sm"
                  >
                    <CheckCircle2 className="size-4 shrink-0 text-success-500" />
                    <span className="flex-1">{criterion.text}</span>
                    <button
                      onClick={() => handleRemoveCriterion(criterion.id)}
                      className="shrink-0 rounded p-1 text-secondary-400 hover:bg-secondary-200 hover:text-danger-500"
                    >
                      <X className="size-3" />
                    </button>
                  </div>
                ))}
              </div>
              <div className="flex gap-2">
                <Input
                  value={newCriterion}
                  onChange={(e) => setNewCriterion(e.target.value)}
                  placeholder="e.g., User can view their profile"
                  onKeyDown={(e) => e.key === "Enter" && handleAddCriterion()}
                />
                <Button size="sm" onClick={handleAddCriterion} disabled={!newCriterion.trim()}>
                  <Plus className="size-4" />
                </Button>
              </div>
              <Button
                size="sm"
                variant="outline"
                className="w-full gap-1"
                onClick={handleGenerateCriteria}
                disabled={isGenerating}
              >
                {isGenerating ? (
                  <>
                    <Loader2 className="size-4 animate-spin" />
                    Generating...
                  </>
                ) : (
                  <>
                    <Sparkles className="size-4" />
                    Generate with AI
                  </>
                )}
              </Button>
            </div>
          </div>
          <DialogFooter>
            <Button onClick={handleSave}>Save</Button>
            <Button variant="outline" onClick={() => setShowEditDialog(false)}>
              Cancel
            </Button>
          </DialogFooter>
        </DialogContent>
      </Dialog>
    </div>
  );
}

