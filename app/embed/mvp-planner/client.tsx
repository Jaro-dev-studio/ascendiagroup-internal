function MvpPlannerInner({ session, userName }: MvpPlannerClientProps) {
  // Restore chat history from session or start fresh
  const initialMessages: ChatMessage[] = useMemo(() => {
    if (
      session.chatHistory &&
      Array.isArray(session.chatHistory) &&
      session.chatHistory.length > 0
    ) {
      return session.chatHistory as ChatMessage[];
    }
    return [];
  }, [session.chatHistory]);

  // Restore flow data from session
  const initialNodes: Node[] = useMemo(() => {
    if (session.flowData) {
      const fd = session.flowData as FlowData;
      if (fd.nodes && fd.nodes.length > 0) {
        return fd.nodes.map((n) => ({
          id: n.id,
          type: n.type,
          position: n.position,
          data: n.data,
        }));
      }
    }
    return [];
  }, [session.flowData]);

  const initialEdges: Edge[] = useMemo(() => {
    if (session.flowData) {
      const fd = session.flowData as FlowData;
      if (fd.edges && fd.edges.length > 0) {
        return fd.edges.map((e) => ({
          id: e.id,
          source: e.source,
          target: e.target,
        }));
      }
    }
    return [];
  }, [session.flowData]);

  const [messages, setMessages] = useState<ChatMessage[]>(initialMessages);
  const [inputValue, setInputValue] = useState("");
  const [isLoading, setIsLoading] = useState(false);
  const [nodes, setNodes, onNodesChange] = useNodesState(initialNodes);
  const [edges, setEdges, onEdgesChange] = useEdgesState(initialEdges);

  // Voice input state
  const [isListening, setIsListening] = useState(false);
  const [voiceSupported, setVoiceSupported] = useState(false);
  const recognitionRef = useRef<SpeechRecognition | null>(null);

  const chatContainerRef = useRef<HTMLDivElement>(null);
  const inputRef = useRef<HTMLTextAreaElement>(null);
  const saveTimeoutRef = useRef<NodeJS.Timeout | null>(null);
  const hasTriggeredInitial = useRef(false);

  // Check voice support
  useEffect(() => {
    const SpeechRecognition =
      window.SpeechRecognition || window.webkitSpeechRecognition;
    setVoiceSupported(!!SpeechRecognition);
  }, []);

  // Quote calculation
  const quoteTotal = useMemo(() => {
    const flowData: FlowData = {
      nodes: nodes.map((n) => ({
        id: n.id,
        type: n.type as FlowNodeData["type"],
        position: n.position,
        data: n.data as FlowNodeData["data"],
      })),
      edges: edges.map((e) => ({
        id: e.id,
        source: e.source,
        target: e.target,
      })),
    };
    return calculateMVPQuote(flowData, defaultConfiguratorData);
  }, [nodes, edges]);

  // Auto-scroll chat
  useEffect(() => {
    if (chatContainerRef.current) {
      chatContainerRef.current.scrollTop =
        chatContainerRef.current.scrollHeight;
    }
  }, [messages, isLoading]);

  // Auto-save (debounced)
  const triggerSave = useCallback(() => {
    if (saveTimeoutRef.current) clearTimeout(saveTimeoutRef.current);
    saveTimeoutRef.current = setTimeout(() => {
      const flowData: FlowData = {
        nodes: nodes.map((n) => ({
          id: n.id,
          type: n.type as FlowNodeData["type"],
          position: n.position,
          data: n.data as FlowNodeData["data"],
        })),
        edges: edges.map((e) => ({
          id: e.id,
          source: e.source,
          target: e.target,
        })),
      };
      saveSession(session.id, flowData, messages, quoteTotal.total);
    }, 2000);
  }, [nodes, edges, messages, quoteTotal.total, session.id]);

  useEffect(() => {
    if (messages.length > 0 || nodes.length > 0) {
      triggerSave();
    }
  }, [messages, nodes, edges, triggerSave]);

  // Trigger initial AI message if no chat history
  useEffect(() => {
    if (hasTriggeredInitial.current) return;
    if (initialMessages.length > 0) return;
    hasTriggeredInitial.current = true;

    const greet = async () => {
      setIsLoading(true);
      try {
        const greeting = userName
          ? `Hi, my name is ${userName}. I just booked a call.`
          : "Hi, I just booked a call.";

        const response = await fetch("/api/chat/mvp-planner", {
          method: "POST",
          headers: { "Content-Type": "application/json" },
          body: JSON.stringify({
            messages: [{ role: "user", content: greeting }],
            currentNodes: [],
          }),
        });

        if (!response.ok) throw new Error("Failed");

        const data = await response.json();
        setMessages([
          { role: "user", content: greeting },
          { role: "assistant", content: data.message },
        ]);

        if (data.blocks && data.blocks.length > 0) {
          addBlocksToGraph(data.blocks, data.edges || []);
        }
      } catch {
        setMessages([
          {
            role: "assistant",
            content:
              "Welcome! I'll help you plan your MVP and give you a rough quote. Tell me about what you're building - what problem does your product solve?",
          },
        ]);
      } finally {
        setIsLoading(false);
      }
    };

    greet();
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  // Add blocks and edges to the graph
  const addBlocksToGraph = useCallback(
    (blocks: BlockData[], newEdges: EdgeData[]) => {
      setNodes((prev) => {
        const existingNames = new Set(
          prev.map((n) => (n.data as FlowNodeData["data"]).name?.toLowerCase())
        );
        const newNodes: Node[] = [];

        for (const block of blocks) {
          if (existingNames.has(block.name.toLowerCase())) continue;
          existingNames.add(block.name.toLowerCase());

          newNodes.push({
            id: `planner-${Date.now()}-${Math.random().toString(36).slice(2, 7)}`,
            type: block.type,
            position: { x: 0, y: 0 },
            data: {
              name: block.name,
              description: block.description,
              isIncluded:
                block.name.toLowerCase() === "dashboard" ||
                block.name.toLowerCase().includes("settings"),
            },
          });
        }

        if (newNodes.length === 0) return prev;

        const combined = [...prev, ...newNodes];
        return autoLayoutNodes(combined);
      });

      if (newEdges && newEdges.length > 0) {
        setEdges((prev) => {
          const allNodes = [...nodes];
          const addedEdges: Edge[] = [];

          for (const e of newEdges) {
            const sourceNode = allNodes.find(
              (n) =>
                (n.data as FlowNodeData["data"]).name?.toLowerCase() ===
                e.sourceName.toLowerCase()
            );
            const targetNode = allNodes.find(
              (n) =>
                (n.data as FlowNodeData["data"]).name?.toLowerCase() ===
                e.targetName.toLowerCase()
            );

            if (sourceNode && targetNode) {
              addedEdges.push({
                id: `edge-${sourceNode.id}-${targetNode.id}`,
                source: sourceNode.id,
                target: targetNode.id,
              });
            }
          }

          return [...prev, ...addedEdges];
        });
      }
    },
    [nodes, setNodes, setEdges]
  );

  // Send message
  const handleSend = useCallback(async () => {
    const text = inputValue.trim();
    if (!text || isLoading) return;

    const newMessages: ChatMessage[] = [
      ...messages,
      { role: "user", content: text },
    ];
    setMessages(newMessages);
    setInputValue("");
    setIsLoading(true);

    // Stop listening if voice is active
    if (isListening) {
      recognitionRef.current?.stop();
      setIsListening(false);
    }

    try {
      const currentNodesSummary = nodes.map((n) => ({
        id: n.id,
        type: n.type as string,
        name: (n.data as FlowNodeData["data"]).name,
        description: (n.data as FlowNodeData["data"]).description,
      }));

      const response = await fetch("/api/chat/mvp-planner", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          messages: newMessages,
          currentNodes: currentNodesSummary,
        }),
      });

      if (!response.ok) throw new Error("Failed to send message");

      const data = await response.json();

      setMessages((prev) => [
        ...prev,
        { role: "assistant", content: data.message },
      ]);

      if (data.blocks && data.blocks.length > 0) {
        addBlocksToGraph(data.blocks, data.edges || []);
      }
    } catch {
      setMessages((prev) => [
        ...prev,
        {
          role: "assistant",
          content: "Sorry, something went wrong. Please try again.",
        },
      ]);
    } finally {
      setIsLoading(false);
    }
  }, [inputValue, isLoading, messages, nodes, isListening, addBlocksToGraph]);

  // Voice toggle
  const toggleVoice = useCallback(() => {
    if (!voiceSupported) return;

    if (isListening) {
      recognitionRef.current?.stop();
      setIsListening(false);
      return;
    }

    const SpeechRecognitionCtor =
      window.SpeechRecognition || window.webkitSpeechRecognition;
    if (!SpeechRecognitionCtor) return;
    const recognition = new SpeechRecognitionCtor();
    recognition.continuous = true;
    recognition.interimResults = true;
    recognition.lang = "en-US";

    recognition.onresult = (event: SpeechRecognitionEvent) => {
      let transcript = "";
      for (let i = 0; i < event.results.length; i++) {
        transcript += event.results[i][0].transcript;
      }
      setInputValue(transcript);
    };

    recognition.onerror = () => {
      setIsListening(false);
    };

    recognition.onend = () => {
      setIsListening(false);
    };

    recognitionRef.current = recognition;
    recognition.start();
    setIsListening(true);
  }, [voiceSupported, isListening]);

  // Handle keyboard shortcuts
  const handleKeyDown = (e: React.KeyboardEvent<HTMLTextAreaElement>) => {
    if (e.key === "Enter" && !e.shiftKey) {
      e.preventDefault();
      handleSend();
    }
  };

  return (
    <div className="flex h-screen flex-col bg-[#F7F7F7]">
      {/* Header */}
      <div className="flex shrink-0 items-center justify-between border-b border-[#E5E5E5] bg-white px-4 py-3 md:px-6">
        <div className="flex items-center gap-3">
          <Image src="/logo.png" alt="Jaro.dev" width={32} height={32} className="size-8" />
          <div>
            <h1 className="text-sm font-semibold text-[#2E2E2E] md:text-base">
              Create your MVP plan
            </h1>
            <p className="text-xs text-[#2E2E2E]/50">
              with Jaro.dev AI - get an instant quote
            </p>
          </div>
        </div>
        <div className="flex items-center gap-2 rounded-lg bg-[#2E2E2E] px-3 py-2 md:px-4">
          <DollarSign className="size-4 text-white" />
          <span className="text-sm font-semibold text-white md:text-base">
            {quoteTotal.total > 0
              ? `$${quoteTotal.total.toLocaleString()}`
              : "$0"}
          </span>
          <span className="hidden text-xs text-white/60 md:inline">
            est. quote
          </span>
        </div>
      </div>

      {/* Main content - split panels */}
      <div className="min-h-0 flex-1">
        {/* Desktop: resizable side-by-side */}
        <div className="hidden h-full md:block">
          <ResizablePanelGroup direction="horizontal">
            <ResizablePanel defaultSize={40} minSize={25} maxSize={60}>
              <ChatPanel
                messages={messages}
                inputValue={inputValue}
                setInputValue={setInputValue}
                isLoading={isLoading}
                isListening={isListening}
                voiceSupported={voiceSupported}
                onSend={handleSend}
                onToggleVoice={toggleVoice}
                onKeyDown={handleKeyDown}
                chatContainerRef={chatContainerRef}
                inputRef={inputRef}
              />
            </ResizablePanel>
            <ResizableHandle withHandle />
            <ResizablePanel defaultSize={60} minSize={30}>
              <DiagramPanel
                nodes={nodes}
                edges={edges}
                onNodesChange={onNodesChange}
                onEdgesChange={onEdgesChange}
              />
            </ResizablePanel>
          </ResizablePanelGroup>
        </div>

        {/* Mobile: stacked with tabs */}
        <MobileLayout
          messages={messages}
          inputValue={inputValue}
          setInputValue={setInputValue}
          isLoading={isLoading}
          isListening={isListening}
          voiceSupported={voiceSupported}
          onSend={handleSend}
          onToggleVoice={toggleVoice}
          onKeyDown={handleKeyDown}
          chatContainerRef={chatContainerRef}
          inputRef={inputRef}
          nodes={nodes}
          edges={edges}
          onNodesChange={onNodesChange}
          onEdgesChange={onEdgesChange}
        />
      </div>
    </div>
  );
}

// ---------- Chat Panel ----------

interface ChatPanelProps {
  messages: ChatMessage[];
  inputValue: string;
  setInputValue: (v: string) => void;
  isLoading: boolean;
  isListening: boolean;
  voiceSupported: boolean;
  onSend: () => void;
  onToggleVoice: () => void;
  onKeyDown: (e: React.KeyboardEvent<HTMLTextAreaElement>) => void;
  chatContainerRef: React.RefObject<HTMLDivElement | null>;
  inputRef: React.RefObject<HTMLTextAreaElement | null>;
}

function ChatPanel({
  messages,
  inputValue,
  setInputValue,
  isLoading,
  isListening,
  voiceSupported,
  onSend,
  onToggleVoice,
  onKeyDown,
  chatContainerRef,
  inputRef,
}: ChatPanelProps) {
  return (
    <div className="flex h-full flex-col bg-white">
      {/* Messages */}
      <div
        ref={chatContainerRef}
        className="flex-1 space-y-4 overflow-y-auto p-4 md:p-6"
      >
        <AnimatePresence initial={false}>
          {messages.map((msg, i) => (
            <motion.div
              key={i}
              initial={{ opacity: 0, y: 10 }}
              animate={{ opacity: 1, y: 0 }}
              transition={{ duration: 0.2 }}
              className={`flex ${msg.role === "user" ? "justify-end" : "justify-start"}`}
            >
              <div
                className={`max-w-[85%] rounded-xl px-4 py-3 text-sm ${
                  msg.role === "user"
                    ? "bg-[#2E2E2E] text-white"
                    : "bg-[#F7F7F7] text-[#2E2E2E]"
                }`}
              >
                {msg.role === "assistant" ? (
                  <ReactMarkdown className="prose prose-sm max-w-none [&_li]:my-0 [&_p]:my-1 [&_ul]:my-1">
                    {msg.content}
                  </ReactMarkdown>
                ) : (
                  msg.content
                )}
              </div>
            </motion.div>
          ))}
        </AnimatePresence>

        {isLoading && (
          <motion.div
            initial={{ opacity: 0 }}
            animate={{ opacity: 1 }}
            className="flex justify-start"
          >
            <div className="flex items-center gap-2 rounded-xl bg-[#F7F7F7] px-4 py-3">
              <Loader2 className="size-4 animate-spin text-[#2E2E2E]/50" />
              <span className="text-sm text-[#2E2E2E]/50">Thinking...</span>
            </div>
          </motion.div>
        )}
      </div>

      {/* Input area */}
      <div className="border-t border-[#E5E5E5] p-3 md:p-4">
        <div className="flex items-end gap-2">
          {voiceSupported && (
            <button
              type="button"
              onClick={onToggleVoice}
              className={`flex size-10 shrink-0 items-center justify-center rounded-lg border transition-all ${
                isListening
                  ? "border-red-300 bg-red-50 text-red-600"
                  : "border-[#E5E5E5] bg-white text-[#2E2E2E]/50 hover:border-[#2E2E2E]/30 hover:text-[#2E2E2E]"
              }`}
            >
              {isListening ? (
                <MicOff className="size-4" />
              ) : (
                <Mic className="size-4" />
              )}
            </button>
          )}
          <div className="relative flex-1">
            <textarea
              ref={inputRef}
              value={inputValue}
              onChange={(e) => setInputValue(e.target.value)}
              onKeyDown={onKeyDown}
              placeholder={
                isListening ? "Listening..." : "Describe your product..."
              }
              rows={1}
              disabled={isLoading}
              className="w-full resize-none rounded-lg border border-[#E5E5E5] bg-white px-4 py-2.5 pr-12 text-sm text-[#2E2E2E] placeholder-[#2E2E2E]/30 outline-none transition-colors focus:border-[#2E2E2E]"
              style={{ minHeight: "42px", maxHeight: "120px" }}
              onInput={(e) => {
                const target = e.target as HTMLTextAreaElement;
                target.style.height = "auto";
                target.style.height = `${Math.min(target.scrollHeight, 120)}px`;
              }}
            />
            {isListening && (
              <div className="absolute right-12 top-1/2 -translate-y-1/2">
                <span className="relative flex size-2.5">
                  <span className="bg-red-400 absolute inline-flex size-full animate-ping rounded-full opacity-75" />
                  <span className="bg-red-500 relative inline-flex size-2.5 rounded-full" />
                </span>
              </div>
            )}
          </div>
          <button
            type="button"
            onClick={onSend}
            disabled={isLoading || !inputValue.trim()}
            className="flex size-10 shrink-0 items-center justify-center rounded-lg bg-[#2E2E2E] text-white transition-all hover:bg-[#1a1a1a] disabled:cursor-not-allowed disabled:opacity-40"
          >
            <Send className="size-4" />
          </button>
        </div>
      </div>
    </div>
  );
}

