// ---------- Layout Helpers ----------

const COLUMN_CONFIG: Record<string, { x: number; label: string }> = {
  page: { x: 50, label: "Pages" },
  externalApi: { x: 350, label: "Integrations" },
  customLogic: { x: 650, label: "Logic" },
};

const Y_START = 30;
const Y_GAP = 120;

function autoLayoutNodes(nodes: Node[]): Node[] {
  const counters: Record<string, number> = { page: 0, externalApi: 0, customLogic: 0 };

  return nodes.map((node) => {
    const col = COLUMN_CONFIG[node.type || "page"] || COLUMN_CONFIG.page;
    const index = counters[node.type || "page"] || 0;
    counters[node.type || "page"] = index + 1;

    return {
      ...node,
      position: { x: col.x, y: Y_START + index * Y_GAP },
    };
  });
}

